from __future__ import annotations

from sqlalchemy import select
from sqlalchemy.orm import Session

from .models import Project


def passport(name: str, domain: str, repo: str, bundle: str, socials: dict[str, dict], assets: dict[str, bool]) -> dict:
    resources = [
        {"key": "domain", "kind": "domain", "label": "Domain", "desired": {"domain": domain}},
        {"key": "website", "kind": "website", "label": "Production website", "desired": {"url": f"https://{domain}"}},
        {"key": "github", "kind": "github_repo", "label": "GitHub repository", "desired": {"repo": repo}},
        {"key": "appstore", "kind": "app_store", "label": "App Store Connect", "desired": {"app_name": name, "bundle_id": bundle, "app_store_id": None}},
    ]
    for platform, state in socials.items():
        resources.append({"key": f"social:{platform}", "kind": "social", "label": platform.title(),
                          "desired": {"platform": platform, **state}})
    for label, done in assets.items():
        key = "asset:" + label.lower().replace(" ", "_")
        if label in {"Privacy policy", "Terms"}:
            filename = "privacy.md" if label == "Privacy policy" else "terms.md"
            title = "Privacy Policy" if label == "Privacy policy" else "Terms of Service"
            content = f"# {title}\n\nProduct: {name}\nWebsite: https://{domain}\n\nDraft generated by SteveJobless. Replace placeholders and obtain appropriate legal review before publication.\n\n## Contact\n\nAdd the canonical support email here.\n"
            resources.append({"key": key, "kind": "local_artifact", "label": label,
                              "desired": {"path": f"generated/{name.lower()}/{filename}", "content": content}})
        else:
            resources.append({"key": key, "kind": "static", "label": label,
                              "desired": {"label": label, "done": done, "executor": "HUMAN"}})
    return {"version": 1, "product": {"name": name, "domain": domain}, "resources": resources}


