def seed(db: Session) -> None:
    for slug, name, domain, repo, bundle, socials, assets in SEEDS:
        existing = db.scalar(select(Project).where(Project.slug == slug))
        if existing:
            continue
        db.add(Project(slug=slug, name=name, domain=domain, passport=passport(name, domain, repo, bundle, socials, assets)))
    db.commit()
    _seed_tradie_kernel(db)


def _seed_tradie_kernel(db: Session) -> None:
    """Tradie demo businesses + kernels from the shared YAMLs (one file drives
    voice BUSINESS_CONFIG and the brain kernel — never fork them)."""
    from pathlib import Path

    from .tradie import TradieKernel

    tenants = [
        ("sparky", "Sparky Electrical", "sparkyelectrical.co.uk", "sparky_electrician_en.yaml",
         [{"key": "channel:whatsapp", "kind": "channel", "label": "WhatsApp", "desired": {"state": "stub"}},
          {"key": "channel:voice", "kind": "channel", "label": "Voice agent", "desired": {"state": "compat"}}]),
        ("flowright", "FlowRight Plumbing", "flowrightplumbing.co.uk", "flowright_plumbing_en.yaml",
         [{"key": "channel:whatsapp", "kind": "channel", "label": "WhatsApp", "desired": {"state": "stub"}}]),
    ]
    for slug, name, domain, yaml_file, resources in tenants:
        project = db.scalar(select(Project).where(Project.slug == slug))
        if project is None:
            project = Project(slug=slug, name=name, domain=domain,
                              passport={"version": 1, "product": {"name": name},
                                        "resources": resources})
            db.add(project)
            db.flush()
        if db.scalar(select(TradieKernel).where(TradieKernel.project_id == project.id)) is None:
            import yaml
            cfg = yaml.safe_load((Path(__file__).parent / "knowledge" / yaml_file).read_text())
            tradie_cfg = cfg.get("tradie", {})
            tradie_cfg.setdefault("hours", (cfg.get("business") or {}).get("hours", {}))
            tradie_cfg.setdefault("autonomy", "observe")
            tradie_cfg.setdefault("retention_days", 90)
            db.add(TradieKernel(project_id=project.id, config=tradie_cfg))
    db.commit()
